import * as fs from "fs";
import { PacketDefs, PacketSignal } from "./schema";

const tabSpaces = 4;

const path = "out/packets.h"

const fileComment = "/** CAN Packet Definitions\n * Auto-generated by Parser/index.ts based on definitions in Parser/packets.yaml\n * DO NOT EDIT\n */\n\n";
const includes = `#pragma once\n\n#include <stdint.h>\n#include <string>\n#include "../../CANPacket.h"\n\n`;

export function genC(defs: PacketDefs) {
    // clear the packet header file
    fs.writeFileSync(path, "");

    // write out the top of the file
    fs.appendFileSync(path, fileComment);
    fs.appendFileSync(path, includes);

    const messages = defs.messages;
    for (let msg of messages) {
        // function comment
        fs.appendFileSync(path, `// ${msg.comment}\n`);

        // function header
        const filteredSignals = msg.signals.filter(e => e.name !== "command");
        fs.appendFileSync(path, cFunctionHeader(msg.name, filteredSignals));

        // declare local variables
        fs.appendFileSync(path, `${cTab(1)}uint64_t contents = 0;\n`);
        fs.appendFileSync(path, `${cTab(1)}uint64_t sizeMask;\n`);
        fs.appendFileSync(path, `${cTab(1)}uint64_t valueInPos;\n`);
        fs.appendFileSync(path, `${cTab(1)}uint32_t floatBits;\n\n`);
        // fill in fields
        for (let sig of msg.signals) {
            fs.appendFileSync(path, `${cTab(1)}// ${sig.name}\n`);
            switch (sig.type) {
                case ("float"):
                    fs.appendFileSync(path, `${cTab(1)}memcpy(&floatBits, &${sig.name}, 4);\n`);
                    fs.appendFileSync(path, `${cTab(1)}valueInPos = (uint64_t)floatBits << ${sig.start};\n`);
                    break;
                case ("uint"):
                    fs.appendFileSync(path, `${cTab(1)}sizeMask = ((1ULL << ${sig.size}) - 1);\n`);
                    fs.appendFileSync(path, `${cTab(1)}valueInPos = ((uint64_t)${sig.name === "command" ? msg.commandId : sig.name} & sizeMask) << ${sig.start};\n`);
                    break;
            }
            fs.appendFileSync(path, `${cTab(1)}contents |= valueInPos;\n\n`);
        }

        // fill in packet fields
        fs.appendFileSync(path, `${cTab(1)}CANPacket_t res = (CANPacket_t){\n`);
        fs.appendFileSync(path, `${cTab(2)}.device = device,\n`);
        // TODO: contentsLength
        fs.appendFileSync(path, `${cTab(1)}};\n`);

        // fill in packet 8-byte contents
        fs.appendFileSync(path, `${cTab(1)}uint8_t* data = &res.command;\n`)
        fs.appendFileSync(path, `${cTab(1)}for (int i = 0; i < 8; i++)\n${cTab(2)}data[i] = (uint8_t)(contents >> (8 * i));\n\n`)

        // function end
        fs.appendFileSync(path, `${cTab(1)}return res;\n}\n\n`);
    }
}


function cFunctionHeader(name: string, signals: PacketSignal[]): string {
    return `inline static CANPacket_t ${name}(CANDevice_t device, ${signals.map(s => cFunctionArg(s)).join(", ")}) {\n`;
}

function cFunctionArg(sig: PacketSignal) {
    return `${cSignalType(sig)} ${sig.name}`;
}

function cSignalType(sig: PacketSignal): string {
    // TODO: handle different byte sizes
    switch (sig.type) {
        case ("bool"):
            return "bool";
        case ("float"):
            return "float";
        case ("int"):
            if (sig.size > 32)
                return "int64_t";
            if (sig.size > 16)
                return "int32_t";
            if (sig.size > 8)
                return "int16_t";
            return "int8_t";
        case ("uint"):
            if (sig.size > 32)
                return "uint64_t";
            if (sig.size > 16)
                return "uint32_t";
            if (sig.size > 8)
                return "uint16_t";
            return "uint8_t";
    }
}

function cTab(n: number): string {
    return " ".repeat(tabSpaces * n);
}
