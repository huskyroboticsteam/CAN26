import * as fs from "fs";
import { PacketDefs, PacketSignal } from "./schema";

const path = "out/packets.h"
const tabSpaces = 4;

const fileComment = "/** CAN Packet Definitions\n * Auto-generated by Parser/index.ts based on definitions in Parser/packets.yaml\n * DO NOT EDIT\n */\n";
const includes = `#pragma once\n\n#include <stdint.h>\n#include <string.h>\n#include "../../CANPacket.h"`;

export function genC(defs: PacketDefs) {
    // clear the packet header file
    fs.writeFileSync(path, "");

    // write out the top of the file
    addLine(fileComment);
    addLine(includes);

    const messages = defs.messages;
    for (let msg of messages) {
        // function comment
        addLine(`\n// ${msg.comment}`);

        // function header
        const filteredSignals = msg.signals.filter(e => e.name !== "command");
        addLine(cFunctionHeader(msg.name, filteredSignals));

        // declare local variables
        addLine(`${cTab(1)}uint64_t contents = 0;`);
        addLine(`${cTab(1)}uint64_t sizeMask;`);
        addLine(`${cTab(1)}uint64_t valueInPos;`);
        addLine(`${cTab(1)}uint32_t floatBits;\n`);

        // fill in fields
        for (let sig of msg.signals) {
            addLine(`${cTab(1)}// ${sig.name}`);
            if (sig.type === "float") {
                addLine(`${cTab(1)}memcpy(&floatBits, &${sig.name}, 4);`);
                addLine(`${cTab(1)}valueInPos = (uint64_t)floatBits << ${sig.start};`);
            }
            else {
                addLine(`${cTab(1)}sizeMask = ((1ULL << ${sig.size}) - 1);`);
                addLine(`${cTab(1)}valueInPos = ((uint64_t)${sig.name === "command" ? msg.commandId : sig.name} & sizeMask) << ${sig.start};`);
            }
            addLine(`${cTab(1)}contents |= valueInPos;\n`);
        }

        // fill in packet fields
        addLine(`${cTab(1)}CANPacket_t res = (CANPacket_t){`);
        addLine(`${cTab(2)}.device = device,`);
        // TODO: contentsLength
        addLine(`${cTab(1)}};`);

        // fill in packet 8-byte contents
        addLine(`${cTab(1)}uint8_t* data = &res.command;`)
        addLine(`${cTab(1)}for (int i = 0; i < 8; i++)\n${cTab(2)}data[i] = (uint8_t)(contents >> (8 * i));\n`)

        // function end
        addLine(`${cTab(1)}return res;\n}`);
    }
}


function cFunctionHeader(name: string, signals: PacketSignal[]): string {
    return `inline static CANPacket_t ${name}(CANDevice_t device, ${signals.map(s => cFunctionArg(s)).join(", ")}) {`;
}

function cFunctionArg(sig: PacketSignal) {
    return `${cSignalType(sig)} ${sig.name}`;
}

function cSignalType(sig: PacketSignal): string {
    switch (sig.type) {
        case ("bool"):
            return "bool";
        case ("float"):
            return "float";  // TODO: handle different sizes of flaot
        case ("int"):
            if (sig.size > 32)
                return "int64_t";
            if (sig.size > 16)
                return "int32_t";
            if (sig.size > 8)
                return "int16_t";
            return "int8_t";
        case ("uint"):
            if (sig.size > 32)
                return "uint64_t";
            if (sig.size > 16)
                return "uint32_t";
            if (sig.size > 8)
                return "uint16_t";
            return "uint8_t";
    }
}

function cTab(n: number): string {
    return " ".repeat(tabSpaces * n);
}

function addLine(text: string, endl: string = "\n") {
    fs.appendFileSync(path, text + endl);
}
